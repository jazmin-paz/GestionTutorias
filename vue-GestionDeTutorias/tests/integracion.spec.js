import { test, expect } from '@playwright/test'

test('registro conserva validaciones, iconos y permite acceder con la cuenta creada', async ({ page }) => {
  const errores = []
  page.on('pageerror', error => errores.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Crear cuenta', exact: true }).click()
  await page.getByRole('button', { name: 'Registrarme', exact: true }).click()
  await expect(page.getByText('Completá este campo.', { exact: true })).toHaveCount(4)
  await expect(page.getByText('Seleccioná una opción.', { exact: true })).toBeVisible()
  await page.getByLabel('Nombre y apellido').fill('Docente de prueba')
  await page.getByLabel('Correo electrónico', { exact: true }).fill('docente@example.com')
  await page.getByRole('combobox', { name: 'Tipo de usuario' }).selectOption('Docente')
  await page.getByLabel('Contraseña', { exact: true }).fill('1234')
  await page.getByLabel('Confirmar contraseña', { exact: true }).fill('otra')
  await expect(page.getByText('Debe tener 8+ caracteres', { exact: false })).toBeVisible()
  await expect(page.getByText('Las contraseñas no coinciden.', { exact: true })).toBeVisible()
  await page.getByLabel('Contraseña', { exact: true }).fill('Prueba123!')
  await page.getByLabel('Confirmar contraseña', { exact: true }).fill('Prueba123!')
  await page.getByRole('button', { name: 'Mostrar contraseña', exact: true }).click()
  await expect(page.getByLabel('Contraseña', { exact: true })).toHaveAttribute('type', 'text')
  expect(await page.locator('.alternar-clave img').evaluateAll(imgs => imgs.every(img => img.complete && img.naturalWidth > 0))).toBe(true)
  await page.getByRole('button', { name: 'Ocultar contraseña', exact: true }).click()
  await expect(page.getByLabel('Contraseña', { exact: true })).toHaveAttribute('type', 'password')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `test-results/registro-${page.viewportSize().width}.png`, fullPage: true })
  await page.getByRole('button', { name: 'Registrarme', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Cuenta creada para Docente de prueba (Docente)')
  await page.getByLabel('Correo electrónico', { exact: true }).fill('docente@example.com')
  await page.getByLabel('Contraseña', { exact: true }).fill('incorrecta')
  await page.getByRole('button', { name: 'Acceder', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('incorrectos')
  await page.getByLabel('Contraseña', { exact: true }).fill('Prueba123!')
  await page.getByRole('button', { name: 'Acceder', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Mis Tutorías' })).toBeVisible()
  await page.getByRole('button', { name: 'Salir', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Inicio de sesión' })).toBeVisible()
  expect(errores).toEqual([])
})

test('panel, cursos, materias y biblioteca mantienen su estado al navegar', async ({ page }) => {
  const errores = []
  page.on('pageerror', error => errores.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Explorar demostración' }).click()
  await page.getByRole('button', { name: '+ Agregar curso', exact: true }).click()
  await page.getByRole('button', { name: '+ Agregar curso', exact: true }).click()
  await page.getByRole('button', { name: 'Curso 4', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Curso 4', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '+ Agregar materia', exact: true }).click()
  await page.getByLabel('Nombre de la materia').fill('Programación')
  await page.getByRole('button', { name: 'Agregar', exact: true }).click()
  await page.getByRole('button', { name: 'Curso 5', exact: true }).click()
  await expect(page.getByText('Programación', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Curso 4', exact: true }).click()
  await expect(page.getByText('Programación', { exact: true })).toBeVisible()
  const mes = await page.locator('.mes h2').textContent()
  await page.getByRole('button', { name: 'Mes siguiente', exact: true }).click()
  await expect(page.locator('.mes h2')).not.toHaveText(mes)
  await page.getByRole('button', { name: 'Mes anterior', exact: true }).click()
  await expect(page.locator('.mes h2')).toHaveText(mes)
  await page.getByRole('button', { name: 'Biblioteca', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Biblioteca', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Observaciones', exact: true }).click()
  await page.getByLabel('Fecha', { exact: true }).fill('2026-10-16')
  await page.getByLabel('Curso', { exact: true }).selectOption({ label: 'Quinto año' })
  await page.getByLabel('Asignatura', { exact: true }).selectOption({ label: 'Informática' })
  await page.getByLabel('Estudiante', { exact: true }).selectOption({ label: 'Mateo González' })
  await page.getByLabel('Contenidos a trabajar', { exact: true }).fill('Variables y funciones')
  await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('guardada durante esta sesión')
  await page.getByLabel('Contenidos a trabajar', { exact: true }).fill('Cambio sin guardar')
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await expect(page.getByLabel('Contenidos a trabajar', { exact: true })).toHaveValue('Variables y funciones')
  await page.getByRole('button', { name: 'Volver', exact: true }).click()
  await page.getByRole('button', { name: 'Observaciones', exact: true }).click()
  await expect(page.getByLabel('Contenidos a trabajar', { exact: true })).toHaveValue('Variables y funciones')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `test-results/observaciones-${page.viewportSize().width}.png`, fullPage: true })
  await page.getByRole('button', { name: 'Mis tutorías', exact: true }).click()
  await expect(page.getByText('Programación', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Eliminar Programación', exact: true }).click()
  await expect(page.getByText('Programación', { exact: true })).toHaveCount(0)
  expect(errores).toEqual([])
})

test('recuperación valida email y explica que no envía correos', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Restablecer contraseña', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill('no-es-email')
  await page.getByRole('button', { name: 'Restablecer contraseña', exact: true }).click()
  await expect(page.getByRole('status')).toBeEmpty()
  await page.getByLabel('Email', { exact: true }).fill('docente@example.com')
  await page.getByRole('button', { name: 'Restablecer contraseña', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('no se envían mensajes')
  await page.getByRole('button', { name: 'Volver a iniciar sesión' }).click()
  await expect(page.getByRole('heading', { name: 'Inicio de sesión' })).toBeVisible()
})
